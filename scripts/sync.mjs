export function normalizeText(value) {
  return value.replace(/\r\n?/g, "\n").replace(/\s+$/u, "") + "\n";
}

export function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

export function parseArgs(argv) {
  const options = {
    check: false,
    help: false,
    agentSkillsSha: null,
    convexEvalsSha: null,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--check") {
      options.check = true;
      continue;
    }
    if (argument === "--help" || argument === "-h") {
      options.help = true;
      continue;
    }
    if (
      argument === "--agent-skills-sha" ||
      argument === "--convex-evals-sha"
    ) {
      const value = argv[index + 1];
      if (!value || value.startsWith("-")) {
        throw new Error(`${argument} requires a full 40-character Git SHA`);
      }
      if (!FULL_SHA.test(value)) {
        throw new Error(`${argument} must be a full 40-character Git SHA`);
      }
      if (argument === "--agent-skills-sha") {
        options.agentSkillsSha = value.toLowerCase();
      } else {
        options.convexEvalsSha = value.toLowerCase();
      }
      index += 1;
      continue;
    }
    throw new Error(`Unknown argument: ${argument}`);
  }

  return options;
}

