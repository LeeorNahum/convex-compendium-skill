function headersForJson() {
  return {
    Accept: "application/vnd.github+json",
    "User-Agent": USER_AGENT,
    ...(process.env.GITHUB_TOKEN
      ? { Authorization: `Bearer ${process.env.GITHUB_TOKEN}` }
      : {}),
  };
}

export async function fetchValidated(
  url,
  { expectedHost, acceptJson = false, fetchImpl = fetch } = {},
) {
  const requested = new URL(url);
  if (requested.protocol !== "https:") {
    throw new Error(`Refusing non-HTTPS source: ${url}`);
  }

  const response = await fetchImpl(url, {
    redirect: "follow",
    headers: acceptJson ? headersForJson() : { "User-Agent": USER_AGENT },
  });
  const finalUrl = new URL(response.url || url);
  if (finalUrl.protocol !== "https:" || finalUrl.hostname !== expectedHost) {
    throw new Error(
      `GET ${url} finished on unexpected host ${finalUrl.hostname || "unknown"}`,
    );
  }
  if (!response.ok) {
    const detail = (await response.text()).slice(0, 500).replace(/\s+/g, " ");
    throw new Error(
      `GET ${url} returned ${response.status} ${response.statusText}${detail ? `: ${detail}` : ""}`,
    );
  }
  return response;
}

async function fetchJson(url, fetchImpl) {
  const response = await fetchValidated(url, {
    expectedHost: "api.github.com",
    acceptJson: true,
    fetchImpl,
  });
  return response.json();
}

async function fetchText(url, fetchImpl) {
  const response = await fetchValidated(url, {
    expectedHost: "raw.githubusercontent.com",
    fetchImpl,
  });
  return normalizeText(await response.text());
}

function validateCommit(value, repo) {
  if (!value || !FULL_SHA.test(value.sha ?? "")) {
    throw new Error(`${repo} returned an invalid commit response`);
  }
  return value.sha.toLowerCase();
}

export function validateTree(value, repo) {
  if (!value || !Array.isArray(value.tree)) {
    throw new Error(`${repo} returned an invalid Git tree`);
  }
  if (value.truncated === true) {
    throw new Error(`${repo} returned a truncated Git tree`);
  }
  const blobs = new Map();
  for (const entry of value.tree) {
    if (
      entry?.type === "blob" &&
      typeof entry.path === "string" &&
      FULL_SHA.test(entry.sha ?? "")
    ) {
      blobs.set(entry.path, entry.sha.toLowerCase());
    }
  }
  return blobs;
}

export async function inspectRepository(config, suppliedSha, fetchImpl) {
  const metadata = await fetchJson(
    `https://api.github.com/repos/${config.name}`,
    fetchImpl,
  );
  if (
    typeof metadata.default_branch !== "string" ||
    typeof metadata.html_url !== "string"
  ) {
    throw new Error(`${config.name} returned invalid repository metadata`);
  }

  const license = metadata.license?.spdx_id ?? null;
  if (config.expectedLicense && license !== config.expectedLicense) {
    throw new Error(
      `${config.name} license is ${license ?? "not detected"}, expected ${config.expectedLicense}`,
    );
  }

  const commitRef = suppliedSha ?? metadata.default_branch;
  const commit = await fetchJson(
    `https://api.github.com/repos/${config.name}/commits/${commitRef}`,
    fetchImpl,
  );
  const sha = validateCommit(commit, config.name);
  if (suppliedSha && sha !== suppliedSha.toLowerCase()) {
    throw new Error(
      `${config.name} resolved ${suppliedSha} to unexpected commit ${sha}`,
    );
  }

  const tree = await fetchJson(
    `https://api.github.com/repos/${config.name}/git/trees/${sha}?recursive=1`,
    fetchImpl,
  );

  return {
    name: config.name,
    url: metadata.html_url,
    defaultBranch: metadata.default_branch,
    license,
    sha,
    blobs: validateTree(tree, config.name),
  };
}

export function validateSourceShape(agentBlobs, evalBlobs) {
  const discovered = new Set();
  for (const sourcePath of agentBlobs.keys()) {
    const match = sourcePath.match(/^skills\/(convex[^/]*)\/SKILL\.md$/);
    if (match) discovered.add(match[1]);
  }

  const expected = new Set([...SKILL_MAP.keys(), ...EXCLUDED_SKILLS]);
  for (const name of expected) {
    if (!discovered.has(name)) {
      throw new Error(`Required upstream Convex skill is missing: ${name}`);
    }
  }
  for (const name of discovered) {
    if (!expected.has(name)) {
      throw new Error(
        `Unmapped upstream Convex skill requires review: ${name}`,
      );
    }
  }

  const outputNames = new Set();
  const sourcesBySkill = new Map();
  for (const [folder, output] of SKILL_MAP) {
    if (outputNames.has(output)) {
      throw new Error(`Two upstream skills map to ${output}`);
    }
    outputNames.add(output);

    const skillPath = `skills/${folder}/SKILL.md`;
    if (!agentBlobs.has(skillPath)) {
      throw new Error(`Required source is missing: ${skillPath}`);
    }
    const prefix = `skills/${folder}/references/`;
    const references = [];
    for (const sourcePath of agentBlobs.keys()) {
      if (!sourcePath.startsWith(prefix)) continue;
      const relative = sourcePath.slice(prefix.length);
      if (!relative.endsWith(".md") || relative.includes("/")) {
        throw new Error(
          `Expected one-level Markdown references for ${folder}, found ${sourcePath}`,
        );
      }
      references.push(sourcePath);
    }
    references.sort();
    sourcesBySkill.set(folder, { skillPath, references, output });
  }

  if (!evalBlobs.has(GUIDELINES_PATH)) {
    throw new Error(`Required source is missing: ${GUIDELINES_PATH}`);
  }

  return sourcesBySkill;
}

export function parseSkillSource(markdown, expectedName) {
  const normalized = normalizeText(markdown);
  if (!normalized.startsWith("---\n")) {
    throw new Error(`${expectedName} SKILL.md has no YAML frontmatter`);
  }
  const end = normalized.indexOf("\n---\n", 4);
  if (end < 0) {
    throw new Error(`${expectedName} SKILL.md has malformed YAML frontmatter`);
  }
  const frontmatter = normalized.slice(4, end);
  const nameMatch = frontmatter.match(/^name:\s*["']?([^"'\n]+)["']?\s*$/m);
  if (!nameMatch || nameMatch[1].trim() !== expectedName) {
    throw new Error(`${expectedName} SKILL.md has mismatched frontmatter name`);
  }
  const body = normalized.slice(end + 5).trimStart();
  if (!/^#\s+\S/m.test(body) || !body.startsWith("# ")) {
    throw new Error(`${expectedName} SKILL.md must begin with an H1`);
  }
  return normalizeText(body);
}

export function stripLeadingH1(markdown) {
  const normalized = normalizeText(markdown);
  if (!normalized.startsWith("# ")) {
    throw new Error("Expected Markdown to begin with an H1");
  }
  const newline = normalized.indexOf("\n");
  return normalizeText(normalized.slice(newline + 1).trimStart());
}

function slugifyHeading(value) {
  return value
    .toLowerCase()
    .replace(/<[^>]+>/g, "")
    .replace(/[`*_~]/g, "")
    .replace(/[^\p{L}\p{N}\s-]/gu, "")
    .trim()
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-");
}

function transformLinesOutsideFences(markdown, transform) {
  let fenced = false;
  let marker = null;
  return markdown
    .split("\n")
    .map((line) => {
      const fence = line.match(/^\s*(```+|~~~+)/);
      if (fence) {
        const current = fence[1][0];
        if (!fenced) {
          fenced = true;
          marker = current;
        } else if (current === marker) {
          fenced = false;
          marker = null;
        }
        return line;
      }
      return fenced ? line : transform(line);
    })
    .join("\n");
}

export function namespaceHeadings(markdown, namespace, levels = 2) {
  const seen = new Map();
  const anchors = new Map();
  const lines = markdown.split("\n");
  let fenced = false;
  let marker = null;
  const output = [];

  for (const line of lines) {
    const fence = line.match(/^\s*(```+|~~~+)/);
    if (fence) {
      const current = fence[1][0];
      if (!fenced) {
        fenced = true;
        marker = current;
      } else if (current === marker) {
        fenced = false;
        marker = null;
      }
      output.push(line);
      continue;
    }

    const heading = !fenced ? line.match(/^(#{1,6})\s+(.+?)\s*$/) : null;
    if (!heading) {
      output.push(line);
      continue;
    }

    const base = slugifyHeading(heading[2]);
    if (!base)
      throw new Error(`Cannot generate an anchor for heading: ${line}`);
    const count = seen.get(base) ?? 0;
    seen.set(base, count + 1);
    const original = count === 0 ? base : `${base}-${count}`;
    const anchor = `${namespace}-${original}`;
    anchors.set(original, anchor);
    output.push(`<a id="${anchor}"></a>`);
    const depth = Math.min(6, heading[1].length + levels);
    output.push(`${"#".repeat(depth)} ${heading[2]}`);
  }

  return { markdown: output.join("\n"), anchors };
}

function targetForReference(name, fragment, referenceInfo) {
  const info = referenceInfo.get(name);
  if (!info)
    throw new Error(`Link points to unknown flattened reference: ${name}`);
  if (!fragment) return `#${info.rootAnchor}`;
  const decoded = decodeURIComponent(fragment);
  const slug = slugifyHeading(decoded);
  const anchor = info.anchors.get(decoded) ?? info.anchors.get(slug);
  if (!anchor) {
    throw new Error(`Link points to unknown heading ${name}.md#${fragment}`);
  }
  return `#${anchor}`;
}

export function rewriteReferenceLinks(markdown, referenceInfo) {
  return transformLinesOutsideFences(markdown, (line) => {
    let rewritten = line.replace(
      /\((?:\.\/)?references\/([^/#\s)]+)\.md(?:#([^\s)"']+))?(\s+["'][^"']*["'])?\)/g,
      (_match, name, fragment, title = "") =>
        `(${targetForReference(name, fragment, referenceInfo)}${title})`,
    );
    rewritten = rewritten.replace(
      /`(?:\.\/)?references\/([^/#`\s]+)\.md(?:#([^`\s]+))?`/g,
      (_match, name, fragment) => {
        const target = targetForReference(name, fragment, referenceInfo);
        return `[${fragment ? `${name} section` : name}](${target})`;
      },
    );
    return rewritten;
  });
}

export function neutralizeInstallerCommands(markdown) {
  let fenced = false;
  let marker = null;
  let replaced = false;
  const lines = markdown.split("\n").map((line) => {
    const fence = line.match(/^\s*(```+|~~~+)/);
    if (fence) {
      const current = fence[1][0];
      if (!fenced) {
        fenced = true;
        marker = current;
      } else if (current === marker) {
        fenced = false;
        marker = null;
      }
      return line;
    }
    if (!EXECUTABLE_INSTALLER.test(line)) return line;
    replaced = true;
    return fenced ? `# ${BUNDLED_GUIDANCE}` : BUNDLED_GUIDANCE;
  });
  return { markdown: lines.join("\n"), replaced };
}

export function assertNoExecutableInstaller(markdown, label = "output") {
  if (EXECUTABLE_INSTALLER.test(markdown)) {
    throw new Error(
      `${label} still contains an executable ai-files installer command`,
    );
  }
}

function assertNoUnresolvedReferences(markdown, label) {
  const prose = transformLinesOutsideFences(markdown, (line) => line);
  if (
    /\((?:\.\/)?references\/[^)]+\.md/i.test(prose) ||
    /`(?:\.\/)?references\/[^`]+\.md/i.test(prose)
  ) {
    throw new Error(
      `${label} still contains an unresolved local reference link`,
    );
  }
}

export function validateGuidelines(markdown) {
  const normalized = normalizeText(markdown);
  if (!normalized.startsWith("# Convex guidelines\n")) {
    throw new Error(
      "Canonical guidelines no longer begin with the expected H1",
    );
  }
  const version = normalized.match(
    /These guidelines target Convex `([^`]+)`\./,
  )?.[1];
  if (!version) {
    throw new Error(
      "Canonical guidelines no longer declare a target Convex range",
    );
  }
  for (const topic of [
    "function",
    "schema",
    "authentication",
    "query",
    "mutation",
    "action",
  ]) {
    if (!new RegExp(`\\b${topic}s?\\b`, "i").test(normalized)) {
      throw new Error(`Canonical guidelines no longer cover ${topic}`);
    }
  }
  return version;
}

function provenanceHeader(title, sourceUrl) {
  return `${GENERATED_BANNER}\n\n# ${title}\n\n_Source: <${sourceUrl}>_\n\n> ${BUNDLED_GUIDANCE}\n`;
}

function titleForSkill(folder) {
  return folder
    .replace(/^convex-/, "")
    .replace(/-/g, " ")
    .replace(/\b\w/g, (character) => character.toUpperCase());
}

export function renderTaskReference({ folder, skillBody, references }) {
  const referenceInfo = new Map();
  const prepared = [];

  for (const reference of references) {
    const name = path.basename(reference.path, ".md");
    if (referenceInfo.has(name)) {
      throw new Error(`Duplicate flattened reference name: ${name}`);
    }
    const rootAnchor = `reference-${slugifyHeading(name)}`;
    const namespaced = namespaceHeadings(
      normalizeText(reference.body).trim(),
      rootAnchor,
      2,
    );
    referenceInfo.set(name, {
      rootAnchor,
      anchors: namespaced.anchors,
    });
    prepared.push({ name, rootAnchor, markdown: namespaced.markdown });
  }

  let body = stripLeadingH1(parseSkillSource(skillBody, folder));
  body = rewriteReferenceLinks(body, referenceInfo);
  body = neutralizeInstallerCommands(body).markdown;

  for (const reference of prepared) {
    let subBody = rewriteReferenceLinks(reference.markdown, referenceInfo);
    subBody = neutralizeInstallerCommands(subBody).markdown;
    body += `\n---\n\n<a id="${reference.rootAnchor}"></a>\n\n## Reference: ${reference.name}\n\n${subBody.trim()}\n`;
  }

  const sourceUrl = `https://github.com/${AGENT_SKILLS_REPO.name}/tree/${AGENT_SKILLS_REPO.branch}/skills/${folder}`;
  const output = normalizeText(
    `${provenanceHeader(`Convex ${titleForSkill(folder)}`, sourceUrl)}\n${body.trim()}`,
  );
  assertNoExecutableInstaller(output, folder);
  assertNoUnresolvedReferences(output, folder);
  return output;
}

export function renderGuidelines(markdown) {
  validateGuidelines(markdown);
  const body = stripLeadingH1(markdown);
  const sourceUrl = `https://github.com/${CONVEX_EVALS_REPO.name}/blob/${CONVEX_EVALS_REPO.branch}/${GUIDELINES_PATH}`;
  const output = normalizeText(
    `${provenanceHeader("Convex Guidelines", sourceUrl)}\n${body.trim()}`,
  );
  assertNoExecutableInstaller(output, "guidelines.md");
  return output;
}

function repositoryManifest(snapshot) {
  return {
    name: snapshot.name,
    url: snapshot.url,
    defaultBranch: snapshot.defaultBranch,
    license: {
      spdx: snapshot.license,
      status:
        snapshot.license === null
          ? "no explicit repository license detected"
          : "detected",
    },
  };
}

export function buildManifest({
  agentSnapshot,
  evalSnapshot,
  targetRange,
  consumedSources,
  outputSources,
  markdownOutputs,
}) {
  const sources = [...consumedSources]
    .sort((a, b) => a.path.localeCompare(b.path))
    .map((source) => ({
      repository: source.repository,
      path: source.path,
      blobSha: source.blobSha,
      sha256: sha256(source.body),
    }));
  const outputs = [...markdownOutputs.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([outputPath, body]) => ({
      path: `references/${outputPath}`,
      sha256: sha256(body),
      sources: [...outputSources.get(outputPath)].sort(),
    }));

  return normalizeText(
    JSON.stringify(
      {
        formatVersion: 1,
        generated: true,
        generator: "scripts/sync.mjs",
        repositories: [
          repositoryManifest(agentSnapshot),
          repositoryManifest(evalSnapshot),
        ].sort((a, b) => a.name.localeCompare(b.name)),
        taskSkills: {
          mapped: Object.fromEntries(SKILL_MAP),
          excluded: [...EXCLUDED_SKILLS].sort(),
        },
        guidelines: {
          path: GUIDELINES_PATH,
          targetConvexRange: targetRange,
        },
        sources,
        outputs,
      },
      null,
      2,
    ),
  );
}

async function readPreviousManifest(referenceDir = REFERENCES) {
  try {
    return JSON.parse(
      await readFile(path.join(referenceDir, "source-manifest.json"), "utf8"),
    );
  } catch (error) {
    if (error?.code === "ENOENT" || error instanceof SyntaxError) return null;
    throw error;
  }
}

function reportLicenseDrift(previous, current) {
  if (!previous?.repositories) return;
  const oldLicenses = new Map(
    previous.repositories.map((repo) => [
      repo.name,
      repo.license?.spdx ?? null,
    ]),
  );
  for (const repo of current.repositories) {
    if (
      oldLicenses.has(repo.name) &&
      oldLicenses.get(repo.name) !== repo.license.spdx
    ) {
      console.warn(
        `license changed for ${repo.name}: ${oldLicenses.get(repo.name) ?? "not detected"} -> ${repo.license.spdx ?? "not detected"}`,
      );
    }
  }
}

export async function compareOutputs(
  outputs,
  referenceDir = REFERENCES,
  fsApi = { readFile, readdir },
) {
  let entries = [];
  try {
    entries = await fsApi.readdir(referenceDir, { withFileTypes: true });
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  const actualFiles = new Set(
    entries.filter((entry) => entry.isFile()).map((entry) => entry.name),
  );
  const actualEntries = new Map(
    entries.map((entry) => [entry.name, entry.isFile()]),
  );
  const expectedFiles = new Set(outputs.keys());
  const missing = [];
  const changed = [];
  const stale = [];

  for (const [name, expected] of outputs) {
    if (!actualFiles.has(name)) {
      missing.push(name);
      continue;
    }
    const actual = await fsApi.readFile(path.join(referenceDir, name), "utf8");
    if (actual !== expected) changed.push(name);
  }
  for (const [name, isFile] of actualEntries) {
    if (!expectedFiles.has(name) || !isFile) stale.push(name);
  }

  return {
    missing: missing.sort(),
    changed: changed.sort(),
    stale: stale.sort(),
  };
}

function isCurrent(diff) {
  return (
    diff.missing.length === 0 &&
    diff.changed.length === 0 &&
    diff.stale.length === 0
  );
}

function describeDiff(diff) {
  const lines = [];
  if (diff.missing.length) lines.push(`missing: ${diff.missing.join(", ")}`);
  if (diff.changed.length) lines.push(`changed: ${diff.changed.join(", ")}`);
  if (diff.stale.length) lines.push(`stale: ${diff.stale.join(", ")}`);
  return lines.join("\n");
}

export async function assertSafeExistingFiles(
  outputs,
  referenceDir,
  previousManifest,
) {
  let entries = [];
  try {
    entries = await readdir(referenceDir, { withFileTypes: true });
  } catch (error) {
    if (error?.code === "ENOENT") return;
    throw error;
  }
  const previouslyOwned = new Set(
    (previousManifest?.outputs ?? []).map((output) =>
      path.basename(output.path),
    ),
  );
  previouslyOwned.add("source-manifest.json");

  for (const entry of entries) {
    if (!entry.isFile()) {
      throw new Error(
        `Refusing to replace unrecognized reference entry: ${entry.name}`,
      );
    }
    if (outputs.has(entry.name) || previouslyOwned.has(entry.name)) {
      continue;
    }
    const body = await readFile(path.join(referenceDir, entry.name), "utf8");
    if (!body.startsWith(GENERATED_BANNER)) {
      throw new Error(
        `Refusing to replace unrecognized hand-authored reference: ${entry.name}`,
      );
    }
  }
}

export async function replaceDirectoryAtomic(
  targetDir,
  outputs,
  fsApi = { mkdir, writeFile, rename, rm },
) {
  const parent = path.dirname(targetDir);
  const token = `${process.pid}-${randomUUID()}`;
  const staging = path.join(parent, `.references-sync-${token}`);
  const backup = path.join(parent, `.references-backup-${token}`);
  let movedExisting = false;

  await fsApi.mkdir(staging, { recursive: true });
  try {
    for (const [name, body] of outputs) {
      await fsApi.writeFile(path.join(staging, name), body, "utf8");
    }
    try {
      await fsApi.rename(targetDir, backup);
      movedExisting = true;
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
    }
    try {
      await fsApi.rename(staging, targetDir);
    } catch (error) {
      if (movedExisting) await fsApi.rename(backup, targetDir);
      throw error;
    }
    if (movedExisting) await fsApi.rm(backup, { recursive: true, force: true });
  } finally {
    await fsApi.rm(staging, { recursive: true, force: true });
  }
}

async function writeGitHubOutput(agentSkillsSha, convexEvalsSha) {
  if (!process.env.GITHUB_OUTPUT) return;
  await appendFile(
    process.env.GITHUB_OUTPUT,
    `agent_skills_sha=${agentSkillsSha}\nconvex_evals_sha=${convexEvalsSha}\n`,
  );
}

export async function generate({
  agentSkillsSha = null,
  convexEvalsSha = null,
  check = false,
  fetchImpl = fetch,
  referenceDir = REFERENCES,
} = {}) {
  const [agentSnapshot, evalSnapshot] = await Promise.all([
    inspectRepository(AGENT_SKILLS_REPO, agentSkillsSha, fetchImpl),
    inspectRepository(CONVEX_EVALS_REPO, convexEvalsSha, fetchImpl),
  ]);

  const sourceMap = validateSourceShape(
    agentSnapshot.blobs,
    evalSnapshot.blobs,
  );
  const rawUrl = (repo, sha, sourcePath) =>
    `https://raw.githubusercontent.com/${repo}/${sha}/${sourcePath}`;
  const required = [];
  for (const { skillPath, references } of sourceMap.values()) {
    required.push({
      repository: agentSnapshot.name,
      sha: agentSnapshot.sha,
      path: skillPath,
      blobSha: agentSnapshot.blobs.get(skillPath),
    });
    for (const sourcePath of references) {
      required.push({
        repository: agentSnapshot.name,
        sha: agentSnapshot.sha,
        path: sourcePath,
        blobSha: agentSnapshot.blobs.get(sourcePath),
      });
    }
  }
  required.push({
    repository: evalSnapshot.name,
    sha: evalSnapshot.sha,
    path: GUIDELINES_PATH,
    blobSha: evalSnapshot.blobs.get(GUIDELINES_PATH),
  });

  const consumedSources = await Promise.all(
    required.map(async (source) => ({
      ...source,
      body: await fetchText(
        rawUrl(source.repository, source.sha, source.path),
        fetchImpl,
      ),
    })),
  );
  const bodies = new Map(
    consumedSources.map((source) => [
      `${source.repository}:${source.path}`,
      source.body,
    ]),
  );

  const markdownOutputs = new Map();
  const outputSources = new Map();
  for (const [folder, config] of sourceMap) {
    const skillBody = bodies.get(`${agentSnapshot.name}:${config.skillPath}`);
    const references = config.references.map((sourcePath) => ({
      path: sourcePath,
      body: bodies.get(`${agentSnapshot.name}:${sourcePath}`),
    }));
    markdownOutputs.set(
      config.output,
      renderTaskReference({ folder, skillBody, references }),
    );
    outputSources.set(config.output, [config.skillPath, ...config.references]);
  }

  const guidelinesBody = bodies.get(`${evalSnapshot.name}:${GUIDELINES_PATH}`);
  const targetRange = validateGuidelines(guidelinesBody);
  markdownOutputs.set("guidelines.md", renderGuidelines(guidelinesBody));
  outputSources.set("guidelines.md", [GUIDELINES_PATH]);

  const manifestBody = buildManifest({
    agentSnapshot,
    evalSnapshot,
    targetRange,
    consumedSources,
    outputSources,
    markdownOutputs,
  });
  const outputs = new Map(markdownOutputs);
  outputs.set("source-manifest.json", manifestBody);

  for (const [name, body] of outputs) {
    if (!body.endsWith("\n")) throw new Error(`${name} has no final newline`);
    if (name.endsWith(".md") && !body.startsWith(GENERATED_BANNER)) {
      throw new Error(`${name} has no generated-file banner`);
    }
  }

  const previousManifest = await readPreviousManifest(referenceDir);
  const currentManifest = JSON.parse(manifestBody);
  reportLicenseDrift(previousManifest, currentManifest);
  if (agentSnapshot.license === null) {
    console.warn(
      `${agentSnapshot.name}: no explicit repository license detected; retaining the approved vendored task model`,
    );
  } else {
    console.warn(
      `${agentSnapshot.name}: repository license ${agentSnapshot.license} is now detected; review the source policy before publication`,
    );
  }

  const diff = await compareOutputs(outputs, referenceDir);
  if (check) {
    if (!isCurrent(diff)) {
      throw new Error(
        `Generated references are not current:\n${describeDiff(diff)}`,
      );
    }
  } else if (!isCurrent(diff)) {
    await assertSafeExistingFiles(outputs, referenceDir, previousManifest);
    await replaceDirectoryAtomic(referenceDir, outputs);
  }

  console.log(
    `${check ? "checked" : isCurrent(diff) ? "unchanged" : "updated"} references/`,
  );
  console.log(`upstream ${agentSnapshot.name} @ ${agentSnapshot.sha}`);
  console.log(`upstream ${evalSnapshot.name} @ ${evalSnapshot.sha}`);
  console.log(`guidelines target Convex ${targetRange}`);
  await writeGitHubOutput(agentSnapshot.sha, evalSnapshot.sha);

  return {
    agentSkillsSha: agentSnapshot.sha,
    convexEvalsSha: evalSnapshot.sha,
    targetRange,
    diff,
    outputs,
  };
}

export async function main(argv = process.argv.slice(2)) {
  const options = parseArgs(argv);
  if (options.help) {
    printHelp();
    return;
  }
  await generate(options);
}

const isEntryPoint =
  process.argv[1] &&
  pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url;
if (isEntryPoint) {
  main().catch((error) => {
    console.error(`Error: ${error.message}`);
    process.exitCode = 1;
  });
}
